def _fine_leapfrog(
    state: tuple[np.ndarray, np.ndarray, np.ndarray],
    masses: np.ndarray,
    g: float,
    softening: float,
    dt: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Advance a (positions, velocities, accelerations) state by ONE step of length dt,
    taken as TWO velocity-Verlet half-steps (the dt/2 shadow used by the drift budget)."""
    pos, vel, acc = state
    h = 0.5 * dt
    for _ in range(2):
        pos = pos + vel * h + 0.5 * acc * h * h
        new_acc = compute_accelerations(pos, masses, g=g, softening=softening)
        vel = vel + 0.5 * (acc + new_acc) * h
        acc = new_acc
    return pos, vel, acc


def _kahan_add(x: np.ndarray, c: np.ndarray, inc: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Compensated (Kahan) x += inc. The carried value is x - c; c holds what rounding dropped so far."""
    y = inc - c
    t = x + y
    return t, (t - x) - y


def _vv_step(state, masses, g, softening, h, comp):
    """One velocity-Verlet step of length h on a (pos, vel, acc, cp, cv) state.
    comp=False reproduces the plain update bit for bit; comp=True carries the rounding error of the
    position and velocity sums (cp, cv) forward instead of throwing it away."""
    pos, vel, acc, cp, cv = state
    if HAVE_NUMBA:  # compiled, identical arithmetic (incl. the Kahan updates)
        return vv_step_kernel(pos, vel, acc, cp, cv, masses, float(g), float(softening) * float(softening), float(h), bool(comp))
    if comp:
        pos, cp = _kahan_add(pos, cp, vel * h + 0.5 * acc * h * h)
    else:
        pos = pos + vel * h + 0.5 * acc * h * h
    new_acc = compute_accelerations(pos, masses, g=g, softening=softening)
    if comp:
        vel, cv = _kahan_add(vel, cv, 0.5 * (acc + new_acc) * h)
    else:
        vel = vel + 0.5 * (acc + new_acc) * h
    return pos, vel, new_acc, cp, cv


def _new_shadow(pos, vel, acc, cp, cv, levels):
    """Fresh shadow(s) from this state: the dt/2 run (levels >= 2) and, for levels == 3, the dt/4 run."""
    def one():
        return (pos.copy(), vel.copy(), acc.copy(), cp.copy(), cv.copy())
    return (one(),) if levels < 3 else (one(), one())


def _advance_shadow(dsh, masses, g, softening, dt, levels, comp):
    """Advance the shadow(s) over ONE coarse step: dt/2 run in 2 substeps, dt/4 run in 4."""
    fine = dsh[0]
    for _ in range(2):
        fine = _vv_step(fine, masses, g, softening, 0.5 * dt, comp)
    if levels < 3:
        return (fine,)
    quarter = dsh[1]
    for _ in range(4):
        quarter = _vv_step(quarter, masses, g, softening, 0.25 * dt, comp)
    return (fine, quarter)


def _repair_one(x, cx, f, cf, q, cq, levels):
    """Richardson-extrapolated (value, compensation) for one array. Written as base + small
    correction so the correction is not swamped by rounding of the O(1) values, and the rounding
    of the final add is kept in the compensation term rather than lost."""
    d_fc = (f - x) - (cf - cx)  # fine - coarse, from the compensated values
    if levels < 3:
        base, cb, corr = f, cf, d_fc / 3.0  # (4f - c)/3 = f + (f - c)/3
    else:
        d_qf = (q - f) - (cq - cf)  # quarter - fine
        base, cb, corr = q, cq, (19.0 * d_qf - d_fc) / 45.0  # (64q - 20f + c)/45 = q + (19(q-f) - (f-c))/45
    t = base + corr
    return t, ((t - base) - corr) + cb


def _repair(pos, vel, cp, cv, dsh, levels, comp):
    """Richardson repair of the coarse state (pos, vel; compensations cp, cv) from the shadows.
    Returns (new_pos, new_vel, new_cp, new_cv, estimated_error). Without compensation and with two
    levels this is exactly the original (4 x_fine - x_coarse) / 3 with its (4/3)|dx| estimate."""
    f = dsh[0]
    if not comp and levels < 3:
        est = (4.0 / 3.0) * position_error(pos, f[0])
        return (4.0 * f[0] - pos) / 3.0, (4.0 * f[1] - vel) / 3.0, cp, cv, est
    q = dsh[1] if levels >= 3 else f
    new_pos, new_cp = _repair_one(pos, cp, f[0], f[3], q[0], q[3], levels)
    new_vel, new_cv = _repair_one(vel, cv, f[1], f[4], q[1], q[4], levels)
    return new_pos, new_vel, new_cp, new_cv, position_error(pos, new_pos)


