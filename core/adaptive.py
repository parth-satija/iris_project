def _make_ias15_sim(
    positions: np.ndarray,
    velocities: np.ndarray,
    masses: np.ndarray,
    g: float,
    softening: float,
    t: float,
) -> rebound.Simulation:
    """Build a REBOUND IAS15 simulation holding exactly the given state at time t."""
    sim = rebound.Simulation()
    sim.integrator = "ias15"
    sim.G = g
    sim.softening = softening
    for m, x, v in zip(masses, positions, velocities):
        sim.add(
            m=float(m),
            x=float(x[0]),
            y=float(x[1]),
            z=float(x[2]),
            vx=float(v[0]),
            vy=float(v[1]),
            vz=float(v[2]),
        )
    sim.t = t
    return sim


def _read_state(sim: rebound.Simulation, n: int) -> tuple[np.ndarray, np.ndarray]:
    """Copy positions/velocities out of a REBOUND simulation as (N,3) arrays."""
    positions = np.empty((n, 3), dtype=np.float64)
    velocities = np.empty((n, 3), dtype=np.float64)
    for i, p in enumerate(sim.particles):
        positions[i] = (p.x, p.y, p.z)
        velocities[i] = (p.vx, p.vy, p.vz)
    return positions, velocities


def _ias15_replay(
    positions: np.ndarray,
    velocities: np.ndarray,
    masses: np.ndarray,
    g: float,
    softening: float,
    start_step: int,
    dt: float,
    n_steps: int,
) -> np.ndarray:
    """
    Positions after `n_steps` IAS15 steps of length dt, starting from the given
    state at step `start_step`. Uses exactly the stepping of the main loop
    (a fresh sim, integrate to each multiple of dt with exact_finish_time).
    """
    if n_steps <= 0:
        return positions.copy()
    sim = _make_ias15_sim(positions, velocities, masses, g, softening, start_step * dt)
    for k in range(1, n_steps + 1):
        sim.integrate((start_step + k) * dt, exact_finish_time=1)
    return _read_state(sim, len(masses))[0]


