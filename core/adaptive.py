"""
core/adaptive.py

The adaptive integrator: advances the system one `dt` at a time with the
cheap custom Leapfrog (Velocity Verlet) by default, and hands the state over
to IAS15 (REBOUND) whenever the safety score says Leapfrog is no longer
trustworthy. Unlike core.leapfrog.run_leapfrog_with_correction, it NEVER
looks at the IAS15 reference trajectory -- it has to decide from its own
state alone, which is the whole point of the safety index.

Per step:

    1. Decide which integrator takes this step, from the safety score of the
       CURRENT state (computed at the end of the previous step):
           in Leapfrog:  switch to IAS15 if score >= safety_threshold
           in IAS15:     stay in IAS15 while score >= release_fraction *
                         safety_threshold, otherwise return to Leapfrog
       (release_fraction < 1 adds hysteresis so the method does not flip
       integrators every step when the score hovers around the threshold;
       1.0 means no hysteresis.) The very first step has no jerk history,
       so it is always taken by Leapfrog.
    2. Advance one dt with that integrator.
    3. Recompute the accelerations, the safety features and the score for
       the new state (features are defined exactly as in the calibration
       data: see core/safety_index.py).

State is transferred between the two integrators through plain positions /
velocities, in both directions. Both use the same frame, G and softening.
A fresh REBOUND simulation is built at each Leapfrog -> IAS15 switch (so
IAS15's adaptive step-size guess restarts there); consecutive IAS15 steps
reuse the same simulation.

Rewinding (optional, rewind=True): detection is often LATE -- by the time the
score crosses the threshold, Leapfrog has already drifted. With rewinding on,
the integrator keeps the last `checkpoint_count` checkpoints (full state +
bookkeeping, in RAM), one every `checkpoint_interval` steps. When the score
reaches the threshold while in Leapfrog, it does NOT switch at the current
state: it restores the checkpoint `rewind_back` places before the latest one
(default 1 = the SECOND-LATEST; the oldest one if fewer exist) and replays from
there with IAS15. Details:

    * IAS15 is forced from the checkpoint up to and including the step at which
      the trigger fired, so every rewind makes net progress (no rewind loops).
      After that the normal release rule applies.
    * Release: IAS15 is kept until the score is below release_fraction *
      safety_threshold, then for `ias15_hold_steps` further steps.
      (ias15_hold_steps also works without rewinding; 0 = release at once.)
    * Everything recorded after the checkpoint (samples, switch events,
      counters, correction count, the stateful index's memory) is discarded and
      regenerated by the replay, so the returned Trajectory / AdaptiveLog
      describe only the final, rewound timeline.

False-positive detection (optional, detect_false_positives=True): a trigger is a
FALSE POSITIVE if IAS15 was not needed, i.e. Leapfrog would have stayed close to
IAS15 the whole time. Detected causally (no reference trajectory): from the
moment an IAS15 stretch starts, a SHADOW Leapfrog is advanced in lockstep from the
same starting state (for a rewind: from the restored checkpoint, so it reproduces
the discarded Leapfrog timeline). Each step, the RMS position difference between
shadow and actual state is tracked. When the stretch ends, if the largest
difference stayed below false_positive_threshold, the stretch is a false positive
(same RMS metric as the correction / error threshold). Detection only: it does not
change what the integrator does. One IAS15Stretch record per stretch is returned in
AdaptiveLog.stretches. Limitation: the verdict only sees the stretch's own
duration (trigger to release, incl. the hold steps); drift that would only have
exceeded the threshold later is not counted against the trigger.

Rollback-depth analysis (optional, analyze_rollback=True; needs rewind=True and an
IAS15 `oracle` trajectory, so it is a validation tool -- the algorithm itself
never sees the oracle): measures how many errors a DEEPER rollback could have
prevented. At every rewind, each checkpoint still in the queue is used as a
counterfactual restore point: IAS15 is replayed from it to the trigger step and
the result is compared with the exact IAS15 state at that step (the oracle,
advanced from its nearest sample). A candidate is EFFECTIVE if its deviation is
at most max(rollback_clean_threshold, (1 - rollback_min_gain) * the deviation of
the un-rewound state), i.e. the rewind removes at least `rollback_min_gain` of the
error (or lands on an essentially exact state). An absolute 'clean' test is not
usable: Leapfrog is never bit-exact, so every queued checkpoint after t=0 would
fail it. Each rewind is then classed:

    adequate         the checkpoint actually used was effective;
    improvable       it was not, but a deeper checkpoint IN THE QUEUE was (a larger
                     rewind_back would have removed more of the error);
    drift_dominated  no queued checkpoint was: the error was accumulated long before
                     the queue's window (slow Leapfrog drift), so no rollback depth
                     inside it can fix it.

Every later error (RMS position error vs the oracle above rollback_error_threshold
at a sample) is attributed to the rewinds since the last clean point (the start,
the last snap back to the reference when correcting, or the last resync):
'improvable' if any of those rewinds was improvable, else 'accumulated_drift' if
any was drift_dominated, else 'after_adequate_rewinds' (rewinds were effective:
chaos / IAS15 divergence / drift after release), else 'undetected' (no rewind at
all: the score never fired).
'improvable' errors are the ones a deeper rollback could have prevented. This is
an attribution, not a proof: it links an error to an insufficient rewind, it does
not re-run the whole simulation with the deeper rollback.

Drift budget (optional, drift_budget > 0): the dominant error of a Leapfrog run is
SLOW accumulated phase drift over thousands of calm steps, which neither the
safety score (it only sees close approaches) nor a short rewind can see or undo.
While in Leapfrog, a shadow Leapfrog with half the step (dt/2) is advanced in
lockstep from the same state. Velocity Verlet is second order, so the coarse
run's accumulated error is ~ (4/3) * RMS|x(dt) - x(dt/2)|. When that estimate
reaches drift_budget * drift_error_threshold, the state is RESYNCED to the
Richardson extrapolation (4 * x_fine - x_coarse) / 3 (same for velocities), which
removes the leading error term, and the shadow restarts from it. Cost ~3 force
evaluations per Leapfrog step instead of 1. Needs no reference. Caveat: the
extrapolation assumes smooth dynamics; close encounters are the safety score's job.

Resync on switch (optional, resync_on_switch=True): the drift budget above only sees
error accumulated INSIDE the current Leapfrog stretch, and an IAS15 handoff freezes
that error into the state (IAS15 only stops it growing), so in practice budget
resyncs almost never fire while every stretch still hands over a contaminated
state. With this option the Richardson extrapolation is applied to the state that
IAS15 takes over from: at every rewind the restored checkpoint is repaired with the
dt/2 shadow saved in it (and at a plain switch the current state is). Each Leapfrog
stretch then ends with a repair, so error cannot pile up from stretch to stretch,
and no long rollback is needed. Implies the dt/2 shadow runs (same cost as the
drift budget); the repaired state also becomes the anchor.

Anchor rewinding (optional, rewind_to_anchor=True): instead of the checkpoint
`rewind_back` places before the latest one, rewind to the ANCHOR, the last state
that was verified: the start, the last resync, the last snap back to the reference
(validation), or the end of an IAS15 stretch that itself started from the anchor.
The replay is IAS15 from there to the trigger step, so it repairs accumulated
drift at the price of a long IAS15 stretch (up to the distance between anchors).
Combine with drift_budget to keep that distance bounded.

Compensated sums (optional, compensated_sums=True): at ~1e-16 per step, double-precision
roundoff in `x += v*dt + ...` and `v += ...` accumulates over the ~200k Leapfrog steps of a run
and becomes the seed that chaos (Lyapunov time ~3) amplifies into a threshold error, long after
the truncation error has been removed by the Richardson repairs. With this option the position
and velocity sums are Kahan-compensated in the main Leapfrog step AND in the shadow runs, the
compensation terms are checkpointed / restored with the state, and the Richardson repair is
written as `base + small correction` with the rounding of that last add kept in the compensation
(so a resync no longer injects ~1e-16 of fresh roundoff). Compensation is reset to zero when the
state comes from REBOUND or from the reference (both are taken as exact). Off (default) the
integration is bit-identical to the version without this option.

Richardson levels (optional, richardson_levels=3): also runs a dt/4 shadow and repairs with the
6th-order combination (64 x_quarter - 20 x_half + x_coarse) / 45 instead of (4 x_half - x_coarse)/3.
Velocity Verlet is symmetric (error series in even powers of dt), so this removes the h^4 term too.
Costs ~7 instead of ~3 force evaluations per Leapfrog step. Without compensated_sums the
extra order is mostly wasted, because roundoff, not truncation, is then the floor.

Note: switching to IAS15 does not repair error Leapfrog has ALREADY
accumulated -- it only stops further accumulation. That is inherent to the
method (there is no reference to snap back to) and is exactly what the
validation experiment measures.
"""

